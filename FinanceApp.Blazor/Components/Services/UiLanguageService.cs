    public string Language { get; private set; } = Russian;
    public event Action? Changed;

    public void SetLanguage(string? language)
    {
        var normalized = string.Equals(language, German, StringComparison.OrdinalIgnoreCase) ? German : Russian;
        if (normalized == Language) return;
        Language = normalized;
        Changed?.Invoke();
    }

    public string T(string key)
    {
        var texts = Language == German ? GermanTexts : RussianTexts;
        return texts.TryGetValue(key, out var text) ? text : key;
    }

    public static string Normalize(string? language) =>
        string.Equals(language, German, StringComparison.OrdinalIgnoreCase) ? German : Russian;
}
